package cf;
import java.util.*;

public class In_Search_of_Convenience {
	
	public static void main(String args[]) {
		
		Scanner sc= new Scanner (System.in);
		
		int t=sc.nextInt();
		
		while(t-->0) {
			
			int x=sc.nextInt();
			
			int y=sc.nextInt();
			
			int r=sc.nextInt();
			
			System.out.print(x+" ");
			
			System.out.println(y+r);
		}
	}

}

